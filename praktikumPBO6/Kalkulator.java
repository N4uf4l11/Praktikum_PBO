public class Kalkulator {
    public int jumlahkan(int a, int b) {
        return a + b;
    }
    
    public double jumlahkan(double a, double b) {
        return a + b;
    }
    
    public int jumlahkan(int a, int b, int c) {
        return a + b + c;
    }
}
